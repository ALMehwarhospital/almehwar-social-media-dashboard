const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const ts = require('typescript');
const moduleObject = { exports: {} };
const code = ts.transpileModule(fs.readFileSync('src/data/inboundCalls.ts', 'utf8').replaceAll('import.meta.env.BASE_URL', '"/"'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
vm.runInNewContext(code, { module: moduleObject, exports: moduleObject.exports });
const { mergeInboundCalls } = moduleObject.exports;
const rows = JSON.parse(fs.readFileSync('public/data/inbound-calls.json','utf8'));
assert.equal(rows.length, 280);
assert.equal(new Set(rows.map(row => row.date)).size, 280);
const sum = month => rows.filter(row => row.periodMonth === month).reduce((total, row) => total + row.inboundCalls, 0);
assert.equal(sum('2026-09'), 10049);
assert.equal(sum('2026-10'), 2354);
assert.equal(rows.filter(row => row.periodMonth === '2026-10').length, 8);
assert(rows.every(row => row.date.startsWith(row.periodMonth)));
const current = rows.find(row => row.date === '2026-10-01');
assert.equal(mergeInboundCalls([current], [{ ...current, sourceVersion: undefined, opdReservations: 999 }])[0].opdReservations, current.opdReservations);
assert.equal(mergeInboundCalls([current], [{ ...current, opdReservations: 0 }])[0].opdReservations, 0);
assert.equal(mergeInboundCalls([current], [{ ...current, opdReservations: null }])[0].opdReservations, null);
assert.equal(mergeInboundCalls([current], [{ ...current, inboundCalls: 280 }])[0].inboundCalls, 280);
assert.equal(mergeInboundCalls(rows, rows).length, 280);
console.log('PASS: daily totals, corrected dates, unique days, missing-day coverage and authoritative manual corrections.');
